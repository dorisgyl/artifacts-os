#!/usr/bin/env node
// Build step (wrangler runs it before every deploy; `npm run check`/`test` too).
//
//  1. seeds/* and templates/* -> src/generated/bundle.ts, so the runtime can
//     create the rules, memory, experience and template repositories on first
//     use without any setup script.
//  2. Preact and htm -> console/vendor/, so the Console loads no third-party
//     script from a CDN.

import { readFileSync, writeFileSync, mkdirSync, readdirSync, statSync, copyFileSync } from "node:fs";
import { join, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));

function walk(dir) {
  const out = {};
  const visit = (d) => {
    for (const name of readdirSync(d).sort()) {
      const p = join(d, name);
      if (statSync(p).isDirectory()) visit(p);
      else out[relative(dir, p).split(sep).join("/")] = readFileSync(p, "utf8");
    }
  };
  visit(dir);
  return out;
}

const bundle = { seeds: {}, templates: {} };
for (const name of readdirSync(join(root, "seeds")).sort()) bundle.seeds[name] = walk(join(root, "seeds", name));
for (const name of readdirSync(join(root, "templates")).sort()) bundle.templates[name] = walk(join(root, "templates", name));

mkdirSync(join(root, "src/generated"), { recursive: true });
writeFileSync(
  join(root, "src/generated/bundle.ts"),
  "// Generated by scripts/bundle-assets.mjs from seeds/ and templates/. Do not edit.\n" +
    "export const BUNDLE: { seeds: Record<string, Record<string, string>>; templates: Record<string, Record<string, string>> } = " +
    JSON.stringify(bundle, null, 1) +
    ";\n",
);

const vendor = join(root, "console/vendor");
mkdirSync(vendor, { recursive: true });
copyFileSync(join(root, "node_modules/preact/dist/preact.module.js"), join(vendor, "preact.module.js"));
copyFileSync(join(root, "node_modules/preact/hooks/dist/hooks.module.js"), join(vendor, "hooks.module.js"));
copyFileSync(join(root, "node_modules/htm/dist/htm.module.js"), join(vendor, "htm.module.js"));

const count = (o) => Object.values(o).reduce((n, files) => n + Object.keys(files).length, 0);
console.log(
  "bundled " + count(bundle.seeds) + " seed files, " + count(bundle.templates) + " template files; vendored preact + htm",
);
